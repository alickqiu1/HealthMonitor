
using Microsoft.EntityFrameworkCore;
using HealthMonitor.Domain.Device;

namespace HealthMonitor.Infrastructure.Data.DeviceContext;

/// <summary>
/// Provides EF Core persistence for the Device bounded context.
/// </summary>
/// <remarks>
/// This DbContext owns the Device inventory tables in the PostgreSQL
/// "device" schema.
///
/// The context manages monitored device identity, inventory metadata,
/// registration timestamps, and soft retirement.
///
/// Telemetry observations, device health state, incidents, and
/// simulation receipts belong to the separate Telemetry bounded context
/// and are not mapped by this context.
///
/// Database connection credentials, migration execution, and runtime
/// database permissions are configured outside this class.
///
/// The Device schema maintains its own EF Core migration history.
/// The migration history table location is configured when the context
/// is registered or created by a design-time factory.
/// </remarks>
public sealed class DeviceDbContext : DbContext
{
    /// <summary>
    /// Gets the monitored device inventory query and persistence set.
    /// </summary>
    public DbSet<MonitoredDevice> Devices => Set<MonitoredDevice>();

    /// <summary>
    /// Initializes the Device persistence context.
    /// </summary>
    /// <param name="options">
    /// EF Core options containing the configured PostgreSQL provider
    /// and database connection.
    /// </param>
    public DeviceDbContext(
        DbContextOptions<DeviceDbContext> options)
        : base(options)
    {
    }

    /// <summary>
    /// Configures the Device schema, entity mappings, and indexes.
    /// </summary>
    /// <param name="modelBuilder">
    /// EF Core model builder used to configure persistence metadata.
    /// </param>
    /// <remarks>
    /// The database mapping preserves the entity's application-generated
    /// GUID identity and enforces required field lengths and asset-tag
    /// uniqueness at the persistence layer.
    ///
    /// The composite site and ID index supports queries that filter
    /// devices by site and order or page by device identifier.
    ///
    /// This configuration intentionally contains no relationships
    /// to entities owned by the Telemetry bounded context.
    /// </remarks>
    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        base.OnModelCreating(modelBuilder);

        // Keep inventory tables within the independently managed Device schema.
        modelBuilder.HasDefaultSchema("device");

        modelBuilder.Entity<MonitoredDevice>(entity =>
        {
            entity.ToTable("monitored_devices", "device");

            entity.HasKey(e => e.Id);

            // Device identifiers are generated by application code,
            // not by PostgreSQL or EF Core.
            entity.Property(e => e.Id)
                .HasColumnName("id")
                .ValueGeneratedNever();

            entity.Property(e => e.AssetTag)
                .HasColumnName("asset_tag")
                .HasMaxLength(64)
                .IsRequired();

            entity.Property(e => e.DisplayName)
                .HasColumnName("display_name")
                .HasMaxLength(120)
                .IsRequired();

            entity.Property(e => e.DeviceType)
                .HasColumnName("device_type")
                .HasMaxLength(32)
                .IsRequired();

            entity.Property(e => e.SiteCode)
                .HasColumnName("site_code")
                .HasMaxLength(32)
                .IsRequired();

            // PostgreSQL timestamptz columns represent UTC instants.
            entity.Property(e => e.CreatedAtUtc)
                .HasColumnName("created_at_utc")
                .HasColumnType("timestamp with time zone")
                .IsRequired();

            // Null indicates an active device; a value indicates retirement.
            entity.Property(e => e.RetiredAtUtc)
                .HasColumnName("retired_at_utc")
                .HasColumnType("timestamp with time zone")
                .IsRequired(false);

            // Enforce uniqueness across the complete device catalog.
            // The domain constructor normalizes asset tags to uppercase.
            entity.HasIndex(e => e.AssetTag)
                .IsUnique()
                .HasDatabaseName("ux_monitored_devices_asset_tag");

            // Support site-based filtering with deterministic ID ordering.
            entity.HasIndex(e => new { e.SiteCode, e.Id })
                .HasDatabaseName("ix_monitored_devices_site_code_id");
        });
    }
}
