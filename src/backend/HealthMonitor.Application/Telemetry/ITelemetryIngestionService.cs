
using System;
using System.Collections.Generic;
using System.Threading;
using System.Threading.Tasks;

namespace HealthMonitor.Application.Telemetry;

/// <summary>
/// Represents a request to generate synthetic telemetry for
/// a selected group of monitored devices.
/// </summary>
/// <param name="BatchId">
/// Caller-generated UUIDv7 identifying the logical request.
/// </param>
/// <param name="Scenario">
/// Canonical simulation scenario: Healthy, HighLatency,
/// HighCpu, or Timeout.
/// </param>
/// <param name="DeviceIds">
/// Identifiers of the devices selected for the simulation.
/// </param>
/// <remarks>
/// The request intentionally does not accept latency, CPU,
/// outcome, or observation timestamps from the caller.
///
/// This prevents clients from injecting arbitrary measurements
/// and ensures that simulation behavior remains deterministic.
///
/// The application service generates measurements from the
/// selected scenario and captures observation time after
/// acquiring the database transaction lock.
///
/// Request shape validation requires 1–25 distinct device IDs.
///
/// Current catalog eligibility is checked only for new requests,
/// after receipt-first replay detection.
/// </remarks>
public sealed record TelemetryIngestionRequest(
    Guid BatchId,
    string Scenario,
    IReadOnlyList<Guid> DeviceIds);

/// <summary>
/// Describes the committed result of a simulation batch.
/// </summary>
/// <param name="BatchId">
/// Original simulation batch identifier.
/// </param>
/// <param name="AffectedDeviceCount">
/// Number of devices affected by the committed operation.
/// </param>
/// <param name="CommittedAtUtc">
/// UTC timestamp stored in the committed simulation receipt.
/// </param>
/// <param name="Replayed">
/// Whether the result was retrieved from an existing receipt
/// rather than generated by a new ingestion operation.
/// </param>
/// <remarks>
/// An identical replay returns the original committed batch
/// information and sets Replayed to true.
///
/// No new telemetry observations, device state changes,
/// or incident transitions occur during a successful replay.
/// </remarks>
public sealed record TelemetryIngestionResult(
    Guid BatchId,
    int AffectedDeviceCount,
    DateTimeOffset CommittedAtUtc,
    bool Replayed);

/// <summary>
/// Coordinates the atomic processing of synthetic telemetry batches.
/// </summary>
/// <remarks>
/// Implements the transaction and replay requirements defined
/// in HealthMonitor Technical Architecture Plan Edition 1.5.
///
/// Processing sequence:
///
/// 1. Validate request shape and calculate its canonical hash.
/// 2. Look up an existing receipt using the supplied BatchId.
/// 3. Return matching receipts or reject conflicting replays.
/// 4. For a new request, validate UUIDv7 age and catalog eligibility.
/// 5. Begin a Telemetry database transaction.
/// 6. Acquire the shared transaction-scoped PostgreSQL advisory lock.
/// 7. Recheck the receipt under the acquired lock.
/// 8. Capture the server observation timestamp.
/// 9. Generate scenario measurements and append telemetry pings.
/// 10. Update the latest persisted device telemetry states.
/// 11. Open, preserve, or resolve qualifying incidents.
/// 12. Persist the completed simulation receipt.
/// 13. Commit all changes atomically.
///
/// Transaction boundaries:
///
/// Steps 1–4 execute before the write transaction begins.
/// They perform preliminary validation and receipt lookup.
///
/// Steps 5–13 execute within one PostgreSQL transaction.
/// The transaction encompasses the final receipt check,
/// telemetry insertion, state updates, incident transitions,
/// and receipt persistence.
///
/// The receipt must be checked again after acquiring the
/// advisory lock because another API instance may have
/// committed the same BatchId between the preliminary
/// receipt lookup and lock acquisition.
///
/// All database modifications must participate in the same
/// transaction and use the same transactional connection.
///
/// Rollback and failure behavior:
///
/// If an exception, cancellation, or validation failure occurs
/// after the transaction begins but before a successful commit,
/// the transaction must be rolled back or disposed without commit.
///
/// Telemetry pings, device state changes, incident changes,
/// and the simulation receipt must either commit together
/// or not be persisted at all.
///
/// Lock acquisition failures must not be treated as successful
/// ingestion. PostgreSQL lock contention is translated by the
/// application/API layers into a service-unavailable response
/// with an appropriate Retry-After header.
///
/// Business decisions:
///
/// Receipt-first replay is required because a previously
/// committed request must remain replayable even if one of
/// its devices has subsequently been retired.
///
/// Matching receipts return the original committed result.
/// Conflicting requests using the same BatchId are rejected
/// without modifying the original batch.
///
/// UUIDv7 freshness and current catalog eligibility are
/// checked only for requests without an existing receipt.
/// A missing receipt for an expired BatchId must not cause
/// that old request to be processed as new work.
///
/// Observation time is captured after acquiring the write
/// lock so concurrent ingestion operations use timestamps
/// consistent with their serialized processing order.
///
/// Concurrency decisions:
///
/// PostgreSQL transaction-scoped advisory locking protects
/// concurrent ingestion across multiple API instances.
///
/// An in-process semaphore alone is insufficient because
/// it cannot coordinate separate application processes.
///
/// The same advisory lock is shared with telemetry retention
/// operations to prevent cleanup from interfering with
/// active ingestion.
///
/// Architectural boundaries:
///
/// This interface exposes no EF Core or PostgreSQL
/// implementation details to callers.
///
/// Request validation, canonical hashing, catalog queries,
/// persistence, locking, and transaction coordination are
/// delegated to the implementation and its dependencies.
///
/// The interface defines the required observable behavior,
/// while the implementation must enforce the specified
/// ordering and consistency guarantees.
/// </remarks>
public interface ITelemetryIngestionService
{
    /// <summary>
    /// Processes a new simulation batch or returns the committed
    /// result of a previously processed identical request.
    /// </summary>
    /// <param name="request">
    /// Batch identifier, canonical scenario, and selected
    /// device identifiers.
    /// </param>
    /// <param name="cancellationToken">
    /// Cancellation token for database and processing operations.
    /// </param>
    /// <returns>
    /// Committed batch information, including whether the
    /// operation was an identical replay.
    /// </returns>
    /// <exception cref="ArgumentNullException">
    /// Thrown when request is null.
    /// </exception>
    /// <remarks>
    /// The implementation validates request shape, supported
    /// scenarios, UUIDv7 age, and device eligibility.
    ///
    /// An existing receipt must be checked before current
    /// catalog eligibility or UUIDv7 freshness validation.
    ///
    /// Matching replays return the original result without
    /// creating telemetry or modifying incident state.
    ///
    /// Conflicting replays must be rejected without modifying
    /// previously committed data.
    ///
    /// For new requests, all telemetry changes and the receipt
    /// must be committed in one database transaction.
    ///
    /// On failure before commit, the transaction must be
    /// rolled back or disposed without committing.
    ///
    /// Cancellation does not guarantee rollback if the
    /// transaction has already committed successfully.
    /// </remarks>
    Task<TelemetryIngestionResult> IngestAsync(
        TelemetryIngestionRequest request,
        CancellationToken cancellationToken = default);
}
